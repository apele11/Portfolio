// Dumps the `projects` collection to src/data/projects.snapshot.ts so the home
// grid can render real cards on first paint instead of waiting for Firestore.
//
// Runs as part of `npm run build`. Failure is non-fatal: if Firestore is
// unreachable (offline, missing env) the previously committed snapshot is left
// in place and the build continues — the live Firestore read still corrects
// whatever is stale.
//
// Only the card subset (`Project` in src/types/project.ts) is written; the
// detail page still reads full documents from Firestore.

import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { loadEnv } from "vite";
import { initializeApp } from "firebase/app";
import { getFirestore, collection, getDocs, terminate } from "firebase/firestore";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "src/data/projects.snapshot.ts");
const SITEMAP = resolve(ROOT, "public/sitemap.xml");

// Keep in step with index.html, public/robots.txt and src/seo.ts.
const SITE_URL = "https://emilyapel.com";

const STATIC_ROUTES = [
  { path: "/", changefreq: "monthly", priority: "1.0" },
  { path: "/about", changefreq: "yearly", priority: "0.8" },
  { path: "/playground", changefreq: "monthly", priority: "0.6" },
];

function str(value, fallback = "") {
  return typeof value === "string" ? value : fallback;
}

/** Mirrors the `Project` card subset — keep in sync with src/types/project.ts. */
function toCard(id, data) {
  const card = {
    id,
    eyebrow: str(data.eyebrow),
    header: str(data.header, "Untitled Project"),
    subtitle: str(data.subtitle),
    coverUrl: str(data.coverUrl),
    order: typeof data.order === "number" ? data.order : 0,
  };
  for (const key of ["color1", "color2", "color3", "color4"]) {
    if (typeof data[key] === "string") card[key] = data[key];
  }
  // Only when set — the grid falls back to the defaults in src/data/coverScrim.ts,
  // and writing them here would churn the file for every document that never
  // touched the sliders.
  for (const key of ["scrimStrength", "scrimWidth"]) {
    if (typeof data[key] === "number" && Number.isFinite(data[key])) card[key] = data[key];
  }
  return card;
}

function bail(reason) {
  console.warn(`[snapshot] ${reason}`);
  if (existsSync(OUT)) {
    console.warn("[snapshot] keeping the existing committed snapshot; build continues.");
    process.exit(0);
  }
  // No snapshot to fall back on — write an empty one so the build still typechecks.
  write([]);
  process.exit(0);
}

const xmlEscape = (s) =>
  s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/**
 * The sitemap is generated from the same read as the snapshot rather than
 * hand-maintained, because project URLs are Firestore document ids — nobody is
 * going to keep a hand-written list of timestamps in step with the CMS.
 *
 * It carries no <lastmod>: a build-stamped date would be a claim about when the
 * content changed rather than when the build ran, and it would rewrite this
 * file on every single build.
 */
function sitemapXml(cards) {
  const entries = [
    ...STATIC_ROUTES,
    ...cards.map((card) => ({
      path: `/projects/${card.id}`,
      changefreq: "yearly",
      priority: "0.9",
    })),
  ];

  const urls = entries
    .map(
      (entry) => `  <url>
    <loc>${xmlEscape(SITE_URL + entry.path)}</loc>
    <changefreq>${entry.changefreq}</changefreq>
    <priority>${entry.priority}</priority>
  </url>`
    )
    .join("\n");

  return `<?xml version="1.0" encoding="UTF-8"?>
<!--
  AUTO-GENERATED by scripts/snapshot-projects.mjs — do not edit by hand.
  Regenerate with \`npm run snapshot\` (also runs as part of \`npm run build\`).
-->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;
}

/**
 * Writes only when the content genuinely differs, so a no-op build leaves the
 * file — and the git diff — alone.
 *
 * Both sides are normalised to LF before comparing. `.gitattributes` sets
 * `* text=auto` and core.autocrlf is on, so a Windows checkout puts these files
 * on disk with CRLF while the bodies here are assembled with LF. Comparing them
 * raw made this guard miss every time, which is how a rewrite landed in the
 * diff after every single build.
 *
 * Neither file carries a build stamp any more, so nothing in either body is
 * generated per-run and byte equality is the whole test. This used to take an
 * `ignore` pattern to mask a timestamp line out of the comparison; the
 * timestamp is gone, so the mask is too.
 */
function writeIfChanged(target, body, label) {
  const normalise = (text) => text.replace(/\r\n/g, "\n");

  if (existsSync(target) && normalise(readFileSync(target, "utf8")) === normalise(body)) {
    console.log(`[snapshot] unchanged: ${label}`);
    return;
  }

  writeFileSync(target, body, "utf8");
  console.log(`[snapshot] wrote: ${label}`);
}

function write(cards) {
  const body = `// AUTO-GENERATED by scripts/snapshot-projects.mjs — do not edit by hand.
// Regenerate with \`npm run snapshot\` (also runs as part of \`npm run build\`).
//
// A build-time copy of the \`projects\` collection, used to paint the home grid
// immediately. Firestore is still the source of truth and overwrites this once
// the live read lands.

import type { Project } from "../types/project";

export const PROJECTS_SNAPSHOT: Project[] = ${JSON.stringify(cards, null, 2)};
`;

  // No build stamp. Nothing ever imported it, and it was the one line that
  // changed for reasons unrelated to the content — so any regeneration that
  // touched the file at all dragged a fresh timestamp into the diff with it.
  // `git log` already answers when this was last regenerated, and answers it
  // accurately.
  writeIfChanged(OUT, body, `src/data/projects.snapshot.ts (${cards.length} projects)`);

  writeIfChanged(
    SITEMAP,
    sitemapXml(cards),
    `public/sitemap.xml (${STATIC_ROUTES.length + cards.length} urls)`
  );
}

const env = loadEnv("production", ROOT, "VITE_");

const firebaseConfig = {
  apiKey: env.VITE_FIREBASE_API_KEY,
  authDomain: env.VITE_FIREBASE_AUTH_DOMAIN,
  projectId: env.VITE_FIREBASE_PROJECT_ID,
  storageBucket: env.VITE_FIREBASE_STORAGE_BUCKET,
  messagingSenderId: env.VITE_FIREBASE_MESSAGING_SENDER_ID,
  appId: env.VITE_FIREBASE_APP_ID,
};

if (!firebaseConfig.apiKey || !firebaseConfig.projectId) {
  bail("VITE_FIREBASE_API_KEY / VITE_FIREBASE_PROJECT_ID missing from the environment.");
}

const app = initializeApp(firebaseConfig);
const db = getFirestore(app);

const timeout = setTimeout(() => bail("Firestore read timed out after 20s."), 20_000);

try {
  const snapshot = await getDocs(collection(db, "projects"));
  clearTimeout(timeout);

  const cards = snapshot.docs
    .map((d) => toCard(d.id, d.data()))
    .sort((a, b) => (a.order ?? 0) - (b.order ?? 0));

  write(cards);
  await terminate(db);
  process.exit(0);
} catch (error) {
  clearTimeout(timeout);
  bail(`Firestore read failed: ${error instanceof Error ? error.message : error}`);
}
