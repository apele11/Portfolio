// Dumps the `projects` collection to src/data/projects.snapshot.ts so the home
// grid can render real cards on first paint instead of waiting for Firestore.
//
// Runs as part of `npm run build`. Failure is non-fatal: if Firestore is
// unreachable (offline, missing env) the previously committed snapshot is left
// in place and the build continues — the live Firestore read still corrects
// whatever is stale.
//
// Only the card subset (`Project` in src/types/project.ts) is written; the
// detail page still reads full documents from Firestore.

import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";
import { loadEnv } from "vite";
import { initializeApp } from "firebase/app";
import { getFirestore, collection, getDocs, terminate } from "firebase/firestore";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = resolve(ROOT, "src/data/projects.snapshot.ts");

function str(value, fallback = "") {
  return typeof value === "string" ? value : fallback;
}

/** Mirrors the `Project` card subset — keep in sync with src/types/project.ts. */
function toCard(id, data) {
  const card = {
    id,
    eyebrow: str(data.eyebrow),
    header: str(data.header, "Untitled Project"),
    subtitle: str(data.subtitle),
    coverUrl: str(data.coverUrl),
    order: typeof data.order === "number" ? data.order : 0,
  };
  for (const key of ["color1", "color2", "color3", "color4"]) {
    if (typeof data[key] === "string") card[key] = data[key];
  }
  return card;
}

function bail(reason) {
  console.warn(`[snapshot] ${reason}`);
  if (existsSync(OUT)) {
    console.warn("[snapshot] keeping the existing committed snapshot; build continues.");
    process.exit(0);
  }
  // No snapshot to fall back on — write an empty one so the build still typechecks.
  write([]);
  process.exit(0);
}

function write(cards) {
  const body = `// AUTO-GENERATED by scripts/snapshot-projects.mjs — do not edit by hand.
// Regenerate with \`npm run snapshot\` (also runs as part of \`npm run build\`).
//
// A build-time copy of the \`projects\` collection, used to paint the home grid
// immediately. Firestore is still the source of truth and overwrites this once
// the live read lands.

import type { Project } from "../types/project";

export const PROJECTS_SNAPSHOT: Project[] = ${JSON.stringify(cards, null, 2)};

export const SNAPSHOT_GENERATED_AT = ${JSON.stringify(new Date().toISOString())};
`;

  // Don't churn the file (and its mtime) when only the timestamp would change.
  if (existsSync(OUT)) {
    const strip = (s) => s.replace(/^export const SNAPSHOT_GENERATED_AT = .*$/m, "");
    if (strip(readFileSync(OUT, "utf8")) === strip(body)) {
      console.log(`[snapshot] unchanged (${cards.length} projects)`);
      return;
    }
  }

  writeFileSync(OUT, body, "utf8");
  console.log(`[snapshot] wrote ${cards.length} projects → src/data/projects.snapshot.ts`);
}

const env = loadEnv("production", ROOT, "VITE_");

const firebaseConfig = {
  apiKey: env.VITE_FIREBASE_API_KEY,
  authDomain: env.VITE_FIREBASE_AUTH_DOMAIN,
  projectId: env.VITE_FIREBASE_PROJECT_ID,
  storageBucket: env.VITE_FIREBASE_STORAGE_BUCKET,
  messagingSenderId: env.VITE_FIREBASE_MESSAGING_SENDER_ID,
  appId: env.VITE_FIREBASE_APP_ID,
};

if (!firebaseConfig.apiKey || !firebaseConfig.projectId) {
  bail("VITE_FIREBASE_API_KEY / VITE_FIREBASE_PROJECT_ID missing from the environment.");
}

const app = initializeApp(firebaseConfig);
const db = getFirestore(app);

const timeout = setTimeout(() => bail("Firestore read timed out after 20s."), 20_000);

try {
  const snapshot = await getDocs(collection(db, "projects"));
  clearTimeout(timeout);

  const cards = snapshot.docs
    .map((d) => toCard(d.id, d.data()))
    .sort((a, b) => (a.order ?? 0) - (b.order ?? 0));

  write(cards);
  await terminate(db);
  process.exit(0);
} catch (error) {
  clearTimeout(timeout);
  bail(`Firestore read failed: ${error instanceof Error ? error.message : error}`);
}
